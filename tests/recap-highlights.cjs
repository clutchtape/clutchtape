const assert = require('node:assert/strict');
const highlights = require('../app/static/recap-highlights.js');
const names = new Set(['alpha']);
const kill = (t, who='Alpha') => ['k', t * 1000, who, 'Other'];
assert.deepEqual(highlights([], names, 60), []);
assert.deepEqual(highlights([kill(10, 'Opponent'), ['m',12000,'Opponent','Overkill']], names, 60), []);
const medals = highlights([kill(4), kill(6), kill(8), ['m',8000,'Alpha','Triple Kill'], ['m',8500,'Alpha','Killing Spree']], names, 60);
assert.equal(medals.length, 1, 'overlapping medals become one stretch');
assert.equal(medals[0].start, 0, 'preroll is clamped at match start');
assert.equal(medals[0].kills, 3);
assert.match(medals[0].title, /Triple Kill|Killing Spree/);
const run = highlights([kill(3),kill(10),kill(20),['k',15000,'Other','Alpha']],names,60);
assert.equal(run[0].title,'Strong stretch');
assert.equal(run[0].deaths,1,'paired deaths are counted');
assert.deepEqual(highlights([kill(10)],names,60),[], 'ordinary lone kills do not create filler highlights');
const objectives = highlights([['o',1000,'Alpha',''],['o',12000,'Alpha','']], names,20);
assert.equal(objectives[0].title,'Objective activity');
assert.equal(objectives[0].end,20);
const many = highlights(Array.from({length:10},(_,i)=>['m',(i*60+20)*1000,'Alpha','Ninja']),names,600);
assert.equal(many.length,6);
assert(many.every((s,i)=>i===0||s.start>many[i-1].end));
console.log('Highlight ranking, player scope, overlap, bounds, counts, empty state: passed');
